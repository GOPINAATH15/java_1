package sample;

public class Relational {

	public static void main(String[] args) {
		int a =10,b=50;
		System.out.println("The value A is "+a+ "The value of B is "+b);
		System.out.println("a>b: "+ (a>b));
		System.out.println("a<b: "+ (a<b));
		System.out.println("a>=b: "+ (a>=b));
		System.out.println("a<=b: "+ (a<=b));
		System.out.println("a==b: "+ (a==b));
		System.out.println("a!=b: "+ (a!=b));
	}
}
